import math
def cosine_lr_schedule(optimizer, epoch, max_epoch, init_lr, min_lr):
    """余弦学习率衰减：随 epoch 从 init_lr 平滑走向 min_lr。"""
    # cos(0)=1，所以初期约为 init_lr；epoch 增长后逐步下降。
    lr = (init_lr - min_lr) * 0.5 * (1. + math.cos(math.pi * epoch / max_epoch)) + min_lr
    # 一个优化器可有多组参数；逐组更新它们的学习率。
    for param_group in optimizer.param_groups:
        param_group['lr'] = lr
        
def warmup_lr_schedule(optimizer, step, max_step, init_lr, max_lr):
    """学习率预热：前 max_step 个 batch 从 init_lr 线性升到 max_lr。"""
    # min 限制上界，即便 step 超过 max_step 也不继续增大。
    lr = min(max_lr, init_lr + (max_lr - init_lr) * step / max_step)
    for param_group in optimizer.param_groups:
        param_group['lr'] = lr    

def step_lr_schedule(optimizer, epoch, init_lr, min_lr, decay_rate):        
    """按 epoch 阶梯衰减学习率，最低不小于 min_lr。"""
    # 例如 decay_rate=0.9 时，第 1 轮是初始值的 0.9 倍。
    lr = max(min_lr, init_lr * (decay_rate**epoch))
    for param_group in optimizer.param_groups:
        param_group['lr'] = lr    
        
